import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('PostgreSQL: ownership, branch isolation, server totals, transitions and retries',async()=>{
 const db=new PGlite();
 const customer='10000000-0000-0000-0000-000000000001';
 const other='10000000-0000-0000-0000-000000000002';
 const staff='10000000-0000-0000-0000-000000000003';
 const outsider='10000000-0000-0000-0000-000000000004';
 const id='20000000-0000-0000-0000-000000000001';
 try{
 await db.exec(`create role anon; create role authenticated; create schema auth; create schema storage;
 create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('app.uid',true),'')::uuid $$;
 create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(bucket_id text,name text); alter table storage.objects enable row level security;
 create function storage.foldername(text) returns text[] language sql immutable as $$ select string_to_array($1,'/') $$;
 grant usage on schema public,auth,storage to anon,authenticated;
 grant select,insert on storage.objects to authenticated;`);
 await db.exec(await readFile(new URL('../supabase/migrations/202611130001_brasa.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../supabase/seed.sql',import.meta.url),'utf8'));
 await db.query('insert into auth.users(id) values ($1),($2),($3),($4)',[customer,other,staff,outsider]);
 await db.query('insert into public.brasa_memberships values ($1,$2)',[staff,'santiago-centro']);
 await db.exec(`insert into public.brasa_branches(id,name) values ('other','Otro local');`);
 await db.query('insert into public.brasa_memberships values ($1,$2)',[outsider,'other']);
 async function as(user,fn){await db.query("select set_config('app.uid',$1,false)",[user]);await db.exec('set role authenticated');try{return await fn();}finally{await db.exec('reset role');}}
 const path=`${customer}/${id}/receipt`;
 await as(customer,()=>db.query("insert into storage.objects values ('brasa-receipts',$1)",[path]));
 const items=JSON.stringify([{productId:'classic',quantity:1,extras:['cheese']}]);
 const create=(total=7690,receipt=path,method='transfer',lines=items)=>db.query('select public.brasa_create_order($1,$2,$3,$4,$5,$6,$7::jsonb,$8,$9,$10) as result',[id,'santiago-centro','Cliente Demo','+56 9 1234 5678','',method,lines,receipt,'sample.png',total]);
 const action=(version,action,reason='')=>db.query('select public.brasa_staff_action($1,$2,$3,$4) as result',[id,version,action,reason]);
 await assert.rejects(as(customer,()=>create(1)),/precios cambiaron/);
 await assert.rejects(as(customer,()=>create(7690,null)),/comprobante válido/);
 await assert.rejects(as(customer,()=>create(7690,path,'transfer',JSON.stringify([{productId:'classic',quantity:1,extras:['cheese','cheese']}]))),/duplicados/);
 const created=await as(customer,()=>create());
 assert.equal(created.rows[0].result.total,7690);
 assert.equal(created.rows[0].result.payment,'review');
 assert.equal(created.rows[0].result.items[0].product.price,6990);
 await as(customer,()=>create());
 assert.equal((await db.query('select count(*)::integer as n from public.brasa_orders')).rows[0].n,1);
 await assert.rejects(as(other,()=>create()),/no disponible/);
 assert.equal((await as(other,()=>db.query('select * from public.brasa_orders'))).rows.length,0);
 assert.equal((await as(outsider,()=>db.query('select * from public.brasa_orders'))).rows.length,0);
 await assert.rejects(as(customer,()=>action(1,'approve')),/Sin permiso/);
 await assert.rejects(as(outsider,()=>action(1,'approve')),/Sin permiso/);
 await assert.rejects(as(staff,()=>action(1,'preparing')),/no permitida/);
 await assert.rejects(as(staff,()=>action(1,'reject','')),/no permitida/);
 await as(staff,()=>action(1,'reject','La imagen no corresponde al pago'));
 const resubmit=()=>db.query('select public.brasa_resubmit_receipt($1,2,$2,$3)',[id,path,'sample.png']);
 await assert.rejects(as(other,resubmit),/Sin acceso/);
 await as(customer,resubmit);
 await as(staff,()=>action(3,'approve'));
 await assert.rejects(as(staff,()=>action(3,'preparing')),/pedido cambió/);
 await as(staff,()=>action(4,'preparing'));
 await assert.rejects(as(staff,()=>action(5,'delivered')),/no permitida/);
 await as(staff,()=>action(5,'ready'));
 await as(staff,()=>action(6,'delivered'));
 await assert.rejects(as(staff,()=>action(7,'cancelled','Prueba')),/cerrado/);
 assert.equal((await as(other,()=>db.query("select * from storage.objects where bucket_id='brasa-receipts'"))).rows.length,0);
 assert.equal((await as(staff,()=>db.query("select * from storage.objects where bucket_id='brasa-receipts'"))).rows.length,1);
 await assert.rejects(as(customer,()=>db.exec("update public.brasa_orders set payload='{}'")),/permission denied/);
 await assert.rejects(as(customer,()=>db.exec("insert into public.brasa_memberships values (auth.uid(),'santiago-centro')")),/permission denied/);
 await assert.rejects(as(customer,()=>db.exec("select public.brasa_set_settings('santiago-centro',true,'{}')")),/Sin permisos/);
 await as(staff,()=>db.exec("select public.brasa_set_settings('santiago-centro',true,array['classic'])"));
 assert.equal((await db.query("select paused from public.brasa_branches where id='santiago-centro'")).rows[0].paused,true);
 }finally{await db.close();}
});
